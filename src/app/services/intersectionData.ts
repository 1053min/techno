/**
 * 교차로 ID로 위치 정보 가져오기
 */
export function getIntersectionLocation(itstId: string): IntersectionLocation | null {
  return INTERSECTION_LOCATIONS[itstId] || null;
}

/**
 * 두 좌표 간 거리 계산 (Haversine formula) - km 단위
 */
function calculateDistance(lat1: number, lng1: number, lat2: number, lng2: number): number {
  const R = 6371;
  const dLat = toRad(lat2 - lat1);
  const dLng = toRad(lng2 - lng1);

  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos(toRad(lat1)) * Math.cos(toRad(lat2)) * Math.sin(dLng / 2) * Math.sin(dLng / 2);

  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return R * c;
}

function toRad(degrees: number): number {
  return (degrees * Math.PI) / 180;
}

/**
 * 주변 교차로 찾기
 */
export function getNearbyIntersections(
  lat: number,
  lng: number,
  radiusKm: number = 2
): IntersectionLocation[] {
  const nearby: IntersectionLocation[] = [];

  Object.values(INTERSECTION_LOCATIONS).forEach((intersection) => {
    const distance = calculateDistance(lat, lng, intersection.lat, intersection.lng);
    if (distance <= radiusKm) {
      nearby.push(intersection);
    }
  });

  // 거리순 정렬
  nearby.sort((a, b) => {
    const distA = calculateDistance(lat, lng, a.lat, a.lng);
    const distB = calculateDistance(lat, lng, b.lat, b.lng);
    return distA - distB;
  });

  return nearby;
}

